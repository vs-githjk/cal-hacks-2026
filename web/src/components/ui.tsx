export type VerdictKind = "veto" | "caution" | "buy" | "out";
const VERDICT: Record<VerdictKind, string> = { veto: "bg-coral-soft text-coral", caution: "bg-amber-soft text-amber", buy: "bg-mint-soft text-mint", out: "bg-slate-soft text-slate" };

export function Verdict({ kind, children }: { kind: VerdictKind; children: ReactNode }) {
  return (
    <span className={`inline-flex h-6 items-center gap-1.5 whitespace-nowrap rounded-full px-2.5 text-[12px] font-medium ${VERDICT[kind]}`}>
      {children}
    </span>
  );
}

export function Code({ children }: { children: ReactNode }) {
  return <code className="rounded-md bg-surface-2 px-1.5 py-px font-mono text-[12px] text-ink-2">{children}</code>;
}

/** Source link: always visible, always the real host. */
export function SourceLink({ href, children }: { href: string; children?: ReactNode }) {
  const text = children ?? href.replace(/^https?:\/\//, "").slice(0, 60);
  if (!safeUrl(href)) return <span className="break-all text-[13px] text-muted">{text || "no source"}</span>;
  return (
    <a href={href} target="_blank" rel="noreferrer" className="break-all text-[13px] font-medium text-pulse underline decoration-pulse/30 underline-offset-2 hover:decoration-pulse">
      {text}
    </a>
  );
}

/** Wraps a card fed from lib/sample.ts because its table is empty or not public yet. The numbers are a recorded run, not this market. */
export function SampleOnly({ on, children }: { on: boolean; children: ReactNode }) {
  if (!on) return <>{children}</>;
  return (
    <div className="relative min-w-0">
      <span className="absolute -top-2.5 right-3 z-10 rounded-full bg-surface shadow-ring"><OriginChip origin="SIM" label="SIM sample, not this market" /></span>
      {children}
    </div>
  );
}

