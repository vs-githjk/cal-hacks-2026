export type Origin = "LIVE" | "MIRROR" | "SIM";

// Design system v2 honesty pills: LIVE is the cyan heartbeat, MIRROR the neutral slate, SIM the amber caution. Each always says its word.
const ORIGIN_STYLE: Record<Origin, string> = {
  LIVE: "bg-live-soft text-ink",
  MIRROR: "bg-slate-soft text-slate",
  SIM: "bg-amber-soft text-amber",
};
const ORIGIN_TITLE: Record<Origin, string> = {
  LIVE: "Made by a real outside party right now",
  MIRROR: "Our agent acting on a real, dated listing",
  SIM: "Generated by us for the demo",
};

/** The LIVE, MIRROR or SIM chip. Anything unrecognised shows as SIM: never assume real. Replaces OriginBadge. */
export function OriginChip({ origin, label }: { origin: string; label?: string }) {
  const o: Origin = origin === "LIVE" || origin === "MIRROR" ? origin : "SIM";
  return (
    <span
      title={ORIGIN_TITLE[o]}
      className={`inline-flex h-5 items-center gap-1 whitespace-nowrap rounded-full px-2 align-middle text-[11px] font-medium leading-none tracking-[0.04em] ${ORIGIN_STYLE[o]}`}
    >
      {o === "LIVE" && <span className="h-1.5 w-1.5 rounded-full bg-live" aria-hidden />}
      {label ?? o}
    </span>
  );
}

/** Condition or variant tag: new, open-box, retail. */
export function Tag({ children }: { children: ReactNode }) {
  return <span className="inline-flex h-6 items-center rounded-full border border-line-2 bg-surface px-2.5 text-[12px] font-medium text-ink">{children}</span>;
}

/** v2 card: white surface, thin line, two soft shadow layers, 16 px padding on a phone and 24 on a desktop.
 * `active` is the one focused card per screen (pulse border plus focus ring). `stripe` is kept for old callers and draws a small
 * coloured dot beside the label instead of a heavy left border. `tactile` lifts 2 px on hover. */
export function Card({ children, className = "", stripe, hero, tactile, active }: { children: ReactNode; className?: string; stripe?: "coral" | "ink" | "amber" | "mint"; hero?: boolean; tactile?: boolean; active?: boolean }) {
  const feel = tactile ? " motion-safe:transition-[transform,box-shadow] motion-safe:duration-150 motion-safe:ease-out motion-safe:hover:-translate-y-0.5" : "";
  return (
    <section data-hero={hero || undefined} data-stripe={stripe} className={`card min-w-0 p-4 md:p-6${active ? " card-active" : ""}${feel} ${className}`}>
      {children}
    </section>
  );
}

/** Card label in the v2 caption style: 12 px, medium, uppercase, muted. The big thing in a card is the number, never the label. */
export function Label({ children }: { children: ReactNode }) {
  return <h2 className="mb-3 text-[12px] font-medium uppercase leading-4 tracking-[0.04em] text-muted">{children}</h2>;
}

