const STYLES: Record<string, string> = {
  LIVE: "bg-emerald-100 text-emerald-900 ring-emerald-600/30 dark:bg-emerald-950 dark:text-emerald-200",
  MIRROR: "bg-sky-100 text-sky-900 ring-sky-600/30 dark:bg-sky-950 dark:text-sky-200",
  SIM: "bg-amber-100 text-amber-900 ring-amber-600/30 dark:bg-amber-950 dark:text-amber-200",
};

const TITLES: Record<string, string> = {
  LIVE: "Made by a real outside party right now",
  MIRROR: "Our agent acting on a real, dated listing",
  SIM: "Generated by us for the demo",
};

/** The LIVE, MIRROR or SIM badge. Anything unrecognised shows as SIM: never assume real. */
export function OriginBadge({ origin }: { origin: string }) {
  const o = origin === "LIVE" || origin === "MIRROR" ? origin : "SIM";
  return (
    <span
      title={TITLES[o]}
      className={`inline-flex items-center rounded px-1.5 py-0.5 font-mono text-[11px] font-semibold tracking-wide ring-1 ring-inset ${STYLES[o]}`}
    >
      {o}
    </span>
  );
}
